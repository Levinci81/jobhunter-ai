// Renders the example outputs in examples/ from the synthetic fixtures (offline).
// Usage: npm run examples
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadWorkflow, runWorkflow } from '../tests/lib/simulator.mjs';
import { ROOT, WORKFLOW_PATH, loadFixtures } from '../tests/lib/paths.mjs';

export function renderExamples() {
  const result = runWorkflow(loadWorkflow(WORKFLOW_PATH), { fixtures: loadFixtures() });
  const [write] = result.sheetWrites;
  const columns = Object.keys(write.rows[0]);
  const csvCell = (v) => `"${String(v).replace(/"/g, '""')}"`;
  const csv = [columns.join(','), ...write.rows.map((row) => columns.map((c) => csvCell(row[c])).join(','))].join('\n') + '\n';

  const [mail] = result.sentEmails;
  const html = `<!doctype html>
<!-- Generated by scripts/render-examples.mjs from synthetic test data. Subject: ${mail.subject} -->
<html lang="de">
<head><meta charset="utf-8"><title>${mail.subject}</title></head>
<body>
${mail.html.trim()}
</body>
</html>
`;
  return { csv, html };
}

if (process.argv[1] && process.argv[1].endsWith('render-examples.mjs')) {
  const { csv, html } = renderExamples();
  writeFileSync(join(ROOT, 'examples', 'sample-sheet-rows.csv'), csv, 'utf8');
  writeFileSync(join(ROOT, 'examples', 'sample-email.html'), html, 'utf8');
  console.log('examples/sample-sheet-rows.csv and examples/sample-email.html written');
}
